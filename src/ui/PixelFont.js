// pre-parse into pixel lists
const GLYPHS = {};
for (const [ch, rows] of Object.entries(G)) {
  const px = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < 5; x++) if (row[x] === '#') px.push(x, y);
  });
  GLYPHS[ch] = px;
}

/** Turn characters the font has no glyph for into ones it has (curly quotes, & ...). */
function normalise(text) {
  return String(text)
    .toUpperCase()
    .replace(/[‘’“”"]/g, "'")
    .replace(/;/g, ',')
    .replace(/&/g, 'AND');
}

/** Calls cb(x, y) for every ink pixel of `text` (x right, y down from the top-left). */
export function glyphPixels(text, cb) {
  text = normalise(text);
  for (let i = 0; i < text.length; i++) {
    const g = GLYPHS[text[i]] || GLYPHS['?'];
    for (let k = 0; k < g.length; k += 2) cb(i * CHAR_W + g[k], g[k + 1]);
  }
}

export const CHAR_W = 6; // 5 + 1 spacing
export const CHAR_H = 7;

export function textWidth(text, scale = 1) {
  return (text.length * CHAR_W - 1) * scale;
}

/**
 * Draw text. align: 'left' | 'center' | 'right'. shadow: colour for a 1px drop shadow (or null).
 */
export function drawText(ctx, text, x, y, color = '#e8e0d0', { scale = 1, align = 'left', shadow = '#0b0a0d' } = {}) {
  text = normalise(text);
  let sx = Math.round(x);
  if (align === 'center') sx = Math.round(x - textWidth(text, scale) / 2);
  else if (align === 'right') sx = Math.round(x - textWidth(text, scale));
  const sy = Math.round(y);
  const pass = (col, ox, oy) => {
    ctx.fillStyle = col;
    for (let i = 0; i < text.length; i++) {
      const g = GLYPHS[text[i]] || GLYPHS['?'];
      const gx = sx + i * CHAR_W * scale + ox;
      for (let k = 0; k < g.length; k += 2) ctx.fillRect(gx + g[k] * scale, sy + g[k + 1] * scale + oy, scale, scale);
    }
  };
  if (shadow) pass(shadow, scale, scale);
  pass(color, 0, 0);
}
